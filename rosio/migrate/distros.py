"""What each ROS 2 distribution ships, read from `data/distros.json`.

The file is generated by `corpus/distros/collect.py` from rosdistro and the official
`ros:<distro>-ros-base` images, never written by hand, so every answer here is a measured
fact about a release and not a recollection of one. It covers the distributions in
`DISTROS`; asking about another one is a usage error, not a guess.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from functools import cache
from pathlib import Path

from rosio.errors import UsageError

DATA = Path(__file__).with_name("data") / "distros.json"

DISTROS = ("humble", "iron", "jazzy", "kilted", "lyrical")
"""Release order. A rule that lands in one distribution applies to every later one."""


def index(distro: str) -> int:
    try:
        return DISTROS.index(distro)
    except ValueError:
        known = ", ".join(DISTROS)
        raise UsageError(f"unknown distribution {distro!r}, rosio knows {known}") from None


def crossed(since: str, start: str, target: str) -> bool:
    """True when moving from `start` to `target` passes the release where a change landed."""
    return index(start) < index(since) <= index(target)


def between(start: str, target: str) -> tuple[str, ...]:
    """The releases a move goes through, the target included and the start not."""
    return DISTROS[index(start) + 1 : index(target) + 1]


@dataclass(frozen=True)
class Header:
    package: str
    present: tuple[str, ...]
    checked: tuple[str, ...]
    warns: tuple[str, ...] = ()
    """Releases where the header is installed and emits a deprecation `#warning`."""

    def known(self, distro: str) -> bool:
        """Whether the owning package was installed where this was measured."""
        return distro in self.checked

    def has(self, distro: str) -> bool:
        return distro in self.present

    def clean(self, distro: str) -> bool:
        """Installed and silent: including it builds without a deprecation warning."""
        return self.has(distro) and distro not in self.warns


@cache
def _facts() -> dict:
    return json.loads(DATA.read_text(encoding="utf-8"))


def toolchain(distro: str) -> dict[str, str]:
    index(distro)
    return dict(_facts()["toolchain"][distro])


def version(distro: str, tool: str) -> tuple[int, ...]:
    """A toolchain version as numbers, `(3, 12)` for the python of jazzy."""
    return tuple(int(part) for part in toolchain(distro)[tool].split("."))


def released(package: str, distro: str) -> bool | None:
    """Whether rosdistro lists the package for the distribution. None for a name rosdistro
    does not know at all, which is a system library or a package of this workspace."""
    index(distro)
    facts = _facts()
    if package in facts["packages"]:
        return distro in facts["packages"][package]
    if package in _everywhere():
        return True
    return None


def first_release(package: str) -> str | None:
    facts = _facts()
    if package in _everywhere():
        return DISTROS[0]
    found = facts["packages"].get(package) or ()
    return found[0] if found else None


def is_ros_package(package: str) -> bool:
    return package in _everywhere() or package in _facts()["packages"]


def header(include: str) -> Header | None:
    """What the images say about one include path, as the code writes it. None when the
    header is the same in every distribution measured, or was never seen."""
    entry = _facts()["headers"].get(include)
    if entry is None:
        return None
    return Header(
        entry["package"],
        tuple(entry["present"]),
        tuple(entry["checked"]),
        tuple(entry.get("warns", ())),
    )


@cache
def _everywhere() -> frozenset[str]:
    return frozenset(_facts()["everywhere"])
