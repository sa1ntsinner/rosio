CHILD_NAMESPACE_RULE = "<child>/<child>"
"""How a child node's fully qualified name is formed under the parent's namespace.

`Costmap2DROS` documents it in costmap_2d_ros.hpp:83, "the node will be placed in a
namespace equal to the node's name", so the controller server's local costmap runs as
`/local_costmap/local_costmap` and a yaml block keyed `local_costmap` twice owns it. Every
row below uses this rule, and a package that ever needs another one states it per row."""


@dataclass(frozen=True)
class KnownName:
    """One (package, executable) to node name row.

    `name` is the literal the source hardcodes. When `randomised` is true the literal is only
    a prefix and the runtime name is longer, so the row states what the node is, not what it
    will be called.
    """

    pkg: str
    executable: str
    name: str
    randomised: bool = False
    verified: bool = True
    evidence: str = ""
    note: str = ""

    @property
    def key(self) -> tuple[str, str]:
        return (self.pkg, self.executable)

    @property
    def joins_on_name(self) -> bool:
        return self.verified and not self.randomised


@dataclass(frozen=True)
class ChildNode:
    """One (package, executable) to child node row.

    A child node is a second ros node created by the executable, whose name a launch file
    never states and whose parameters live in a yaml block of their own. Without this table
    those blocks match no launched node and read as owner_name_mismatch, which is 116 false
    positives on the reference stack.
    """

    pkg: str
    executable: str
    child: str
    rule: str = CHILD_NAMESPACE_RULE
    verified: bool = True
    evidence: str = ""
    note: str = ""

    @property
    def key(self) -> tuple[str, str]:
        return (self.pkg, self.executable)

    def fqn(self, namespace: str = "/") -> str:
        """The fully qualified name under a parent namespace, by this row's rule."""
        tail = "/".join(
            self.child if part == "<child>" else part for part in self.rule.split("/") if part
        )
        return f"{namespace.rstrip('/')}/{tail}"


