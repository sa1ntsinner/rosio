"""Node names that third party executables hardcode, as committed data.

The reference stack launches many nodes with no `name=`, so the declared layer knows the
package and the executable and nothing else, while the parameter files key on the runtime
name. Without this table those nodes join on nothing and every parameter block on them reads
as drift. The table is data with a citation per row, not a heuristic: a row that could not be
checked against the installed sources is marked `verified = False` and is never used to mint
a name.

Two rows exist to say the opposite thing. `tf2_ros/static_transform_publisher` builds its
name as the literal prefix `static_transform_publisher_` plus a runtime suffix, and an
unnamed `rviz2` is created through an anonymous name path that appends the process id and a
clock reading. Those are exactly the nodes that own the frame layer, so joining them on name
merges unrelated publishers and fabricates TF edges. Use `joins_on_name` before comparing a
name with anything, and identify a randomised family by its role digest.

How the rows were checked. ROS humble ships these packages as binaries, so the check is the
name literal in the string table of the executable or of the library holding the node class,
plus, where it exists, an upstream launch file that states the name it expects. Two shapes
appear. A hand written `main` carries the literal in its own executable
(`robot_localization/ekf_node` holds `ekf_filter_node`). A `main` generated by
`rclcpp_components_register_node` carries only the executable name, and the node name literal
lives in the component library: `nav2_map_server/map_saver_server` holds `map_saver_server`
while `libmap_server_core.so` holds `map_saver`, and `nav2_bringup/launch/slam_launch.py`
confirms `map_saver` by listing it in `lifecycle_nodes` for exactly that executable.

`CHILD_TABLE` answers a second question with the same evidence rule: which further nodes an
executable creates for itself. A costmap is a full ros node that no launch file names, so a
yaml block keyed on it owns a node the launch layer never saw, and the whole block reads as
a name mismatch until this table binds it.
"""

from __future__ import annotations

from dataclasses import dataclass

