"""Child nodes an executable creates for itself, as committed data.

Checked the same way as the name table: the literal in the library or the executable that
holds the node class, plus the upstream header that states how the child namespace is
formed. `nav2_smoother`, `nav2_behaviors`, `nav2_collision_monitor`, `nav2_bt_navigator`
and `nav2_amcl` were checked the same way and hold no costmap literal, so they get no row.
"""


INDEX: dict[tuple[str, str], KnownName] = {row.key: row for row in TABLE}

CHILD_INDEX: dict[tuple[str, str], tuple[ChildNode, ...]] = {
    key: tuple(row for row in CHILD_TABLE if row.key == key)
    for key in sorted({row.key for row in CHILD_TABLE})
}


def rows() -> tuple[KnownName, ...]:
    """The table sorted by (package, executable), which is how it is compared."""
    return tuple(sorted(TABLE, key=lambda row: row.key))


def lookup(pkg: str, executable: str) -> KnownName | None:
    return INDEX.get((str(pkg), str(executable)))


def name_for(pkg: str, executable: str) -> str | None:
    """The node name to use, or None when the table cannot answer.

    None covers three cases that must not be guessed apart: no row, an unverified row, and a
    row whose runtime name is randomised.
    """
    row = lookup(pkg, executable)
    if row is None or not row.joins_on_name:
        return None
    return row.name


def name_prefix(pkg: str, executable: str) -> str | None:
    """The stable prefix of a randomised name, for a readable label only."""
    row = lookup(pkg, executable)
    if row is None or not row.randomised:
        return None
    return row.name


def is_randomised(pkg: str, executable: str) -> bool:
    row = lookup(pkg, executable)
    return bool(row and row.randomised)


def joins_on_name(pkg: str, executable: str) -> bool:
    """False for anything randomised or unverified, so a caller cannot join by accident."""
    row = lookup(pkg, executable)
    return bool(row and row.joins_on_name)


def packages() -> tuple[str, ...]:
    return tuple(sorted({row.pkg for row in TABLE} | {row.pkg for row in CHILD_TABLE}))


def child_rows(pkg: str, executable: str) -> tuple[ChildNode, ...]:
    """Every child row for one executable, unverified ones included, sorted by child name."""
    found = CHILD_INDEX.get((str(pkg), str(executable)), ())
    return tuple(sorted(found, key=lambda row: row.child))


def child_nodes(pkg: str, executable: str) -> tuple[str, ...]:
    """The child node names this executable creates, or an empty tuple.

    Only verified rows are returned, so a caller cannot bind a parameter block to a child
    that was never confirmed to exist.
    """
    return tuple(row.child for row in child_rows(pkg, executable) if row.verified)


